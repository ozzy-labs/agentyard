#!/bin/bash
# scripts/lib/agentsmd.sh
# User-scope AGENTS.md (ADR-0007 §5).
# Source of truth: ~/.agents/AGENTS.md. agentyard creates a minimal template
# when missing, never edits user content, and keeps a generated "host
# environment" block at the end. Each installed agent is wired to it:
#
#   claude       ~/.claude/CLAUDE.md block: @~/.agents/AGENTS.md
#                https://code.claude.com/docs/en/memory
#   antigravity  ~/.gemini/AGENTS.md block: @[agentyard](~/.agents/AGENTS.md)
#                https://antigravity.google/docs/rules
#   copilot      COPILOT_CUSTOM_INSTRUCTIONS_DIRS += $HOME/.agents (env.sh)
#                https://docs.github.com/en/copilot/how-tos/copilot-cli/add-custom-instructions
#   codex        ~/.codex/AGENTS.md: symlink when missing, else reference block
#                https://learn.chatgpt.com/docs/agent-configuration/agents-md
#   gemini       ~/.gemini/GEMINI.md: symlink when missing, else reference block
#                (its @import cannot reach outside ~/.gemini)
# Agent settings files are never edited. ~/.claude/AGENTS.md is never created.
# Requires lib/core.sh, lib/state.sh, lib/block.sh, lib/agents.sh, lib/select.sh.

agents_md_source() { printf '%s/.agents/AGENTS.md' "$HOME"; }

_agents_md_template() {
  cat <<'EOF'
# AGENTS.md (user scope)

<!--
Personal instructions shared by all your AI coding agents
(Claude Code, Codex, Copilot CLI, Antigravity CLI, Gemini CLI).
Write them under "My instructions" below. Text inside HTML comments like
this one is ignored by agents. agentyard only manages the block at the end
of this file.
-->

## My instructions

<!-- Examples: preferred reply language, commit message conventions, things agents must never do. -->

EOF
}

# Facts about this host that help agents avoid common mistakes.
_agents_md_host_block() {
  local tools="" t
  for t in git git-lfs gh jq rg fd fzf tree docker aws az gcloud ast-grep yq markitdown bun tmux zellij; do
    has_cmd "$t" && tools="${tools:+$tools, }$t"
  done
  printf '## Host environment (generated by agentyard)\n\n'
  printf -- '- OS: %s\n' "$(_agents_md_os_label)"
  printf -- '- Runtimes are managed by mise. In a repository, run `mise install` to get the pinned versions.\n'
  printf -- '- Python: use `uv` (`uv run`, `uv add`, `uvx`). The system `pip` is blocked (PEP 668).\n'
  printf -- '- Node.js: npm and pnpm are available. Use the package manager the repository specifies.\n'
  printf -- '- Available CLIs: %s\n' "${tools:-none}"
  if [ "$(os_kind)" = "linux" ]; then
    if has_cmd bwrap && has_cmd socat; then
      printf -- '- Sandbox: bubblewrap and socat are installed.\n'
    fi
  fi
}

_agents_md_os_label() {
  case "$(os_kind)" in
  linux)
    local label
    label="Ubuntu $(os_release_get VERSION_ID 2>/dev/null || printf '?') ($(normalized_arch))"
    is_wsl && label="$label on WSL2"
    printf '%s' "$label"
    ;;
  macos) printf 'macOS %s (%s)' "$(sw_vers -productVersion 2>/dev/null)" "$(normalized_arch)" ;;
  esac
}

agents_md_ensure_source() {
  local src
  src="$(agents_md_source)"
  if [ ! -e "$src" ]; then
    mkdir -p "$(dirname "$src")"
    _agents_md_template >"$src"
    state_add created "$src"
    state_add setting agents-md-template "$(_agents_md_checksum "$src")"
    log_ok "$src を作成しました"
  fi
  block_upsert "$src" "$(_agents_md_host_block)" md
}

_agents_md_checksum() {
  cksum <"$1" | awk '{ print $1 }'
}

# _agents_md_link_or_reference <agent-file>
# Symlink to the source when the file is missing; otherwise append a block
# asking the agent to read the source (best effort, the agent decides).
_agents_md_link_or_reference() {
  local file="$1" src
  src="$(agents_md_source)"
  if [ -L "$file" ] && [ "$(readlink "$file")" = "$src" ]; then
    log_skip "$file は正本へのシンボリックリンクです"
    return 0
  fi
  if [ ! -e "$file" ]; then
    mkdir -p "$(dirname "$file")"
    ln -s "$src" "$file"
    state_add symlink "$file"
    log_ok "$file -> $src"
    return 0
  fi
  block_upsert "$file" "Also read and follow the user's shared instructions in ~/.agents/AGENTS.md." md
  if [ "$BLOCK_CHANGED" = "1" ]; then
    log_ok "$file に参照を追記しました（読み込みはエージェント次第）"
  else
    log_skip "$file には参照を追記済みです"
  fi
}

agents_md_wire() {
  local claude_dir="${CLAUDE_CONFIG_DIR:-$HOME/.claude}"
  local codex_dir="${CODEX_HOME:-$HOME/.codex}"
  local gemini_dir="$HOME/.gemini"

  if agent_present claude; then
    block_upsert "$claude_dir/CLAUDE.md" "@~/.agents/AGENTS.md" md
    if [ "$BLOCK_CHANGED" = "1" ]; then
      log_ok "Claude Code: $claude_dir/CLAUDE.md から読み込み"
    else
      log_skip "Claude Code: 連携済みです"
    fi
  fi

  if agent_present codex; then
    _agents_md_link_or_reference "$codex_dir/AGENTS.md"
  fi

  if agent_present gemini; then
    _agents_md_link_or_reference "$gemini_dir/GEMINI.md"
  fi

  if agent_present antigravity; then
    # Antigravity also reads ~/.gemini/GEMINI.md. When that is already a
    # symlink to the source, adding an include would load it twice.
    if [ -L "$gemini_dir/GEMINI.md" ] && [ "$(readlink "$gemini_dir/GEMINI.md")" = "$(agents_md_source)" ]; then
      log_skip "Antigravity CLI: ~/.gemini/GEMINI.md 経由で読み込まれます（二重読み込みを防ぐため追加しません）"
    else
      block_upsert "$gemini_dir/AGENTS.md" "@[agentyard](~/.agents/AGENTS.md)" md
      if [ "$BLOCK_CHANGED" = "1" ]; then
        log_ok "Antigravity CLI: $gemini_dir/AGENTS.md から読み込み"
      else
        log_skip "Antigravity CLI: 連携済みです"
      fi
    fi
  fi

  if agent_present copilot; then
    state_add setting copilot-dirs 1
    log_ok "Copilot CLI: COPILOT_CUSTOM_INSTRUCTIONS_DIRS に ~/.agents を追加（env.sh）"
  fi
}

install_agents_md() {
  log_section "AGENTS.md (ユーザースコープ)"
  agents_md_ensure_source
  agents_md_wire
}

# Regenerate only the host environment block (used by update).
agents_md_refresh() {
  [ -f "$(agents_md_source)" ] || return 0
  block_present "$(agents_md_source)" md || return 0
  block_upsert "$(agents_md_source)" "$(_agents_md_host_block)" md
}
